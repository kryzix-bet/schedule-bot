def category_of(title):
    l = title.lower()
    cats = []
    if "утренн" in l: cats.append("morning")
    if "вечерн" in l: cats.append("evening")
    if "верх" in l or "низ" in l or "full body" in l or "подтяг" in l or "силов" in l: cats += ["transformation","strength"]
    if "аэробн" in l or "кондицион" in l: cats += ["transformation","running"]
    if "ходьб" in l: cats += ["transformation","running"]
    if "осанк" in l or "профил" in l: cats.append("transformation")
    if "восстановлен" in l or "отдых" in l or "прогулк" in l or "замеры" in l: cats.append("transformation")
    if "олимпиад" in l: cats.append("olympiad")
